-- 老库升级专用：只放独立新增表的幂等 DDL。
-- 执行时机在 main_tables.sql（仅空库）之后、schema 完整性校验之前，
-- 因此这里不能引用任何基表，也不能包含依赖既有数据结构的函数。
-- 新库由 main_tables.sql / main_indexes.sql 建表，重复执行无害。

CREATE TABLE IF NOT EXISTS antigravity_relay_failures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at DOUBLE PRECISION NOT NULL,
    credential_name TEXT NOT NULL,
    status_code INTEGER,
    tag TEXT NOT NULL,
    reason TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_relay_failure_time ON antigravity_relay_failures(created_at);
