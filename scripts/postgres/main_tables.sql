CREATE FUNCTION delete_credential_telemetry() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    DELETE FROM antigravity_telemetry_profiles WHERE account_id = OLD.id;
    DELETE FROM antigravity_telemetry_events WHERE account_id = OLD.id;
    RETURN OLD;
END
$$;
CREATE TRIGGER delete_credential_telemetry AFTER DELETE ON antigravity_credentials
FOR EACH ROW EXECUTE FUNCTION delete_credential_telemetry();
