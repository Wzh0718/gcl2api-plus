CREATE TABLE credentials (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                filename TEXT UNIQUE NOT NULL,
                credential_data TEXT NOT NULL,

                -- 状态字段
                disabled BIGINT DEFAULT 0,
                error_codes TEXT DEFAULT '[]',
                error_messages TEXT DEFAULT '[]',
                last_success DOUBLE PRECISION,
                user_email TEXT,

                -- 模型级 CD 支持 (JSON: {model_name: cooldown_timestamp})
                model_cooldowns TEXT DEFAULT '{}',

                -- preview 状态 (只对 geminicli 有效，默认为 true)
                preview BIGINT DEFAULT 1,

                -- tier 状态 (只对 geminicli 有效，默认为 pro)
                tier TEXT DEFAULT 'pro',

                -- 轮换相关
                rotation_order BIGINT DEFAULT 0,
                call_count BIGINT DEFAULT 0,

                -- 时间戳
                created_at DOUBLE PRECISION DEFAULT (floor(extract(epoch FROM statement_timestamp()))),
                updated_at DOUBLE PRECISION DEFAULT (floor(extract(epoch FROM statement_timestamp())))
            );

CREATE TABLE antigravity_credentials (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
